/**
 * Get all available visual elements
 */
export function getAllVisualElements(): string[] {
  const allElements: string[] = [];

  // Add all emojis
  for (const category of Object.values(EMOJI_CATEGORIES)) {
    allElements.push(...category);
  }

  // Add all unicode symbols
  for (const category of Object.values(UNICODE_SYMBOLS)) {
    allElements.push(...category);
  }

  // Add position indicators
  for (const category of Object.values(POSITION_INDICATORS)) {
    allElements.push(...category);
  }

  return [...new Set(allElements)]; // Remove duplicates
}

/**
 * Get visual elements by category
 */
function getVisualElementsByCategory(category: keyof typeof EMOJI_CATEGORIES): string[] {
  return EMOJI_CATEGORIES[category] || [];
}

const DEFAULT_RANDOM_COUNT = 10;

/**
 * Get random visual elements for inspiration
 */
function getRandomVisualElements(count: number = DEFAULT_RANDOM_COUNT): string[] {
  const all = getAllVisualElements();
  const shuffled = [...all].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, count);
}

const MAX_ELEMENTS_TO_SHOW = 20;
const MAX_SYMBOLS_TO_SHOW = 10;

/**
 * Format visual library for AI prompts
 */
export function formatVisualLibraryForPrompt(): string {
  const categoryLines: string[] = [];
  for (const [name, elements] of Object.entries(EMOJI_CATEGORIES)) {
    const displayElements = elements.slice(0, MAX_ELEMENTS_TO_SHOW).join(" ");
    const moreIndicator = elements.length > MAX_ELEMENTS_TO_SHOW ? "..." : "";
    categoryLines.push(`${name}: ${displayElements}${moreIndicator}`);
  }

  return `AVAILABLE VISUAL ELEMENTS:
${categoryLines.join("\n")}

UNICODE SYMBOLS:
- Arrows: ${UNICODE_SYMBOLS.arrows.slice(0, MAX_SYMBOLS_TO_SHOW).join(" ")}...
- Math: ${UNICODE_SYMBOLS.math.slice(0, MAX_SYMBOLS_TO_SHOW).join(" ")}...
- Shapes: ${UNICODE_SYMBOLS.shapes.slice(0, MAX_SYMBOLS_TO_SHOW).join(" ")}...

POSITION INDICATORS:
- Above: ${POSITION_INDICATORS.above.join(" ")}
- Below: ${POSITION_INDICATORS.below.join(" ")}
- Left/Right: ${POSITION_INDICATORS.left.join(" ")} / ${POSITION_INDICATORS.right.join(" ")}
- Inside/Outside: ${POSITION_INDICATORS.inside.join(" ")} / ${POSITION_INDICATORS.outside.join(" ")}

You have access to HUNDREDS of visual elements. Use them creatively to build complex, multi-layered rebus puzzles!`;
}
